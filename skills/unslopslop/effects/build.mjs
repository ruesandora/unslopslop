// Each demo is one self-contained HTML file (no network, no dependencies), so it can be copied anywhere.
// Usage: node effects/build.mjs            (all effects)
//        node effects/build.mjs ribbed-glass (one)
import { readFileSync, writeFileSync, readdirSync, existsSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

