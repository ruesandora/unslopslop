#!/usr/bin/env node
// Builds every effects/<name>/demo.html from effects/<name>/effect.js and the shared runtime.
// Each demo is one self-contained HTML file (no network, no dependencies), so it can be copied anywhere.
// Usage: node effects/build.mjs            (all effects)
//        node effects/build.mjs ribbed-glass (one)
import { readFileSync, writeFileSync, readdirSync, existsSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const runtime = readFileSync(join(root, '_runtime/fx.js'), 'utf8');
const only = process.argv[2];

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const pick = (src, key) => {
  const m = src.match(new RegExp(key + ":\\s*'((?:[^'\\\\]|\\\\.)*)'"));
  return m ? m[1].replace(/\\'/g, "'") : '';
};

const shell = ({ slug, title, summary, cost, fallback, slop, effect }) => `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(title)} · effects library</title>
<meta name="description" content="${esc(summary)}">
<!-- Generated by effects/build.mjs from effects/${slug}/effect.js. Edit that file, then rebuild. -->
<style>
  :root { --ground: #0e0e10; --panel: #17171a; --line: #2a2a2f; --ink: #ecebe6; --soft: #b9b8b1; --accent: #e7c46a; color-scheme: dark; }
  * { box-sizing: border-box; }
  html, body { margin: 0; height: 100%; background: var(--ground); color: var(--ink); font: 15px/1.55 system-ui, -apple-system, "Segoe UI", sans-serif; }
  .wrap { display: grid; grid-template-columns: minmax(0, 1fr) 340px; height: 100vh; }
  #stage { position: relative; overflow: hidden; background: #000; }
  #stage canvas { position: absolute; inset: 0; width: 100%; height: 100%; display: block; }
  .nogl { position: absolute; left: 24px; bottom: 16px; margin: 0; max-width: 40ch; color: #fff; }
  aside { border-left: 1px solid var(--line); background: var(--panel); overflow: auto; padding: 24px 24px 32px; }
  .back { color: var(--soft); text-decoration: none; font-size: 13px; }
  .back:hover, .back:focus-visible { color: var(--ink); }
  h1 { font-size: 26px; line-height: 1.15; margin: 16px 0 8px; font-weight: 600; letter-spacing: -0.01em; }
  .sum { margin: 0 0 24px; color: var(--soft); }
  .ctl { display: grid; gap: 6px; margin: 0 0 16px; }
  .ctl label { display: flex; justify-content: space-between; gap: 12px; font-size: 13px; color: var(--ink); }
  .ctl output { font: 12px/1.6 ui-monospace, SFMono-Regular, Menlo, monospace; color: var(--accent); font-variant-numeric: tabular-nums; }
  .ctl small { color: var(--soft); font-size: 13px; }
  input[type=range] { width: 100%; accent-color: var(--accent); min-height: 24px; }
  select, input[type=file], button { font: inherit; font-size: 14px; color: var(--ink); background: #212126; border: 1px solid var(--line); border-radius: 8px; padding: 8px 12px; min-height: 40px; }
  button { cursor: pointer; }
  button:hover { border-color: #4a4a52; }
  :focus-visible { outline: 2px solid var(--accent); outline-offset: 2px; }
  .group { border-top: 1px solid var(--line); margin-top: 24px; padding-top: 16px; }
  .notes { font-size: 13px; color: var(--soft); }
  .notes dt { color: var(--ink); margin-top: 12px; }
  .notes dd { margin: 2px 0 0; }
  .shot .wrap { grid-template-columns: 1fr; }
  .shot aside { display: none; }
  @media (max-width: 760px) {
    .wrap { grid-template-columns: 1fr; height: auto; }
    #stage { height: 62vh; min-height: 320px; }
    aside { border-left: 0; border-top: 1px solid var(--line); padding: 20px 16px 32px; }
    .shot #stage { height: 100vh; }
  }
</style>
</head>
<body>
<div class="wrap">
  <main id="stage"></main>
  <aside>
    <a class="back" href="../index.html">All effects</a>
    <h1>${esc(title)}</h1>
    <p class="sum">${esc(summary)}</p>
    <div id="controls"></div>
    <div class="group">
      <div class="ctl"><label for="src">Source</label>
        <select id="src"><option value="gradient">Generated gradient</option><option value="scene">Test scene</option><option value="upload" disabled>Your image</option></select></div>
      <div class="ctl"><label for="pal">Palette</label>
        <select id="pal"><option value="dusk">Dusk</option><option value="ember">Ember</option><option value="seaglass">Sea glass</option><option value="graphite">Graphite</option><option value="moss">Moss</option></select></div>
      <div class="ctl"><label for="upload">Try your own image (stays in this browser)</label><input id="upload" type="file" accept="image/*"></div>
      <div class="ctl"><button id="play" type="button">Pause motion</button></div>
    </div>
    <dl class="notes group">
      <dt>Cost</dt><dd>${esc(cost)}</dd>
      <dt>Fallback</dt><dd>${esc(fallback)}</dd>
      <dt>Becomes slop when</dt><dd>${esc(slop)}</dd>
    </dl>
  </aside>
</div>
<script>
${runtime}
</script>
<script>
${effect}
</script>
</body>
</html>
`;

let n = 0;
for (const name of readdirSync(root)) {
  const dir = join(root, name);
  if (!statSync(dir).isDirectory() || name.startsWith('_')) continue;
  if (only && name !== only) continue;
  const file = join(dir, 'effect.js');
  if (!existsSync(file)) continue; // CSS-only effects keep a hand-written demo.html
  const effect = readFileSync(file, 'utf8');
  const meta = { slug: name, effect };
  for (const k of ['title', 'summary', 'cost', 'fallback', 'slop']) meta[k] = pick(effect, k);
  writeFileSync(join(dir, 'demo.html'), shell(meta));
  n++;
}
console.log(`built ${n} demo${n === 1 ? '' : 's'}`);
