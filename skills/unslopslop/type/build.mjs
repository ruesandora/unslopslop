function md(recipes) {
  const out = ['# Type recipes', '', 'Generated by `build.mjs` from `<id>/recipe.mjs`. Read `README.md` first for the selection procedure.', ''];
  for (const [g, name] of GROUPS) {
    const list = recipes.filter((r) => r.group === g);
    if (!list.length) continue;
    out.push(`## ${name}`, '');
    for (const r of list) {
      const f = r.fonts;
      out.push(`### ${r.id} · ${r.name}`, '');
      out.push(`- Faces: display **${f.display.family}**, text **${f.text.family}**${f.mono ? `, mono **${f.mono.family}**` : ''}${f.accent ? `, accent **${f.accent.family}** (${f.accent.role || 'one place only'})` : ''}. Licence: ${[...new Set(ROLES.map((k) => f[k]?.licence).filter(Boolean))].join(', ')}.`);
      out.push(`- Mood: ${r.mood.join(', ')} · domains: ${r.domains.join(', ')} · moves: ${r.moves.join(', ')}`);
      out.push(`- Ladder (role: 1440 / 390 px, line height, tracking, weight):`);
      for (const [role, d, m, lh, tr, w, face] of r.ladder) out.push(`  - ${role}: ${d} / ${m}, ${lh}, ${tr} em, ${w} (${face})`);
      out.push(`- Case: ${r.case}`);
      out.push(`- Numerals and features: \`${r.features.css}\`. ${r.features.note}`);
      out.push(`- Signature: ${r.signature}`);
      out.push(`- Use when: ${r.use}`);
      out.push(`- Turns into slop when: ${r.slop}`);
      out.push(`- Specimen: [\`${r.id}/specimen.html\`](${r.id}/specimen.html) · screenshot \`${r.id}/screenshot.jpg\``, '');
    }
  }
  return out.join('\n');
}

