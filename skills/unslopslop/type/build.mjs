#!/usr/bin/env node
// Builds the type library from type/<id>/recipe.mjs:
//   type/<id>/specimen.html   live specimen (fonts from Google Fonts, system fallbacks offline)
//   type/index.html           gallery, grouped by mood
//   type/recipes.md           every recipe as plain text, for agents that cannot render a page
// Usage: node type/build.mjs
import { readdirSync, existsSync, writeFileSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
export const GROUPS = [
  ['editorial', 'Editorial', 'Magazines, essays, long reads, publishers.'],
  ['technical', 'Technical', 'Developer tools, research, infrastructure.'],
  ['data-dense', 'Data-dense', 'Dashboards, tables, operations screens.'],
  ['finance', 'Finance', 'Money, invoices, banking, ledgers.'],
  ['civic', 'Civic and institutional', 'Public services, museums, universities, archives.'],
  ['health', 'Health', 'Clinics, care, wellbeing, medical forms.'],
  ['children', 'Children', 'Reading, learning and play for young users.'],
  ['playful', 'Playful', 'Toys, games, consumer apps with a grin.'],
  ['luxury', 'Luxury', 'Fashion, jewellery, hotels, fragrance.'],
  ['warm-craft', 'Warm craft', 'Bakeries, makers, small producers, food.'],
  ['retro', 'Retro', 'Arcade, diner, heritage and revival.'],
  ['brutalist', 'Brutalist and zine', 'Raw structure, punk, protest, artist sites.'],
  ['culture', 'Culture and events', 'Music, festivals, sport, posters, social.'],
  ['calm', 'Calm and quiet', 'Meditation, poetry, slow brands, systems that whisper.'],
];

const esc = (s) => String(s ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const ROLES = ['display', 'text', 'mono', 'accent'];
// Move families shown as gallery filters (a recipe may list other, finer moves too).
export const FAMILIES = ['serif display', 'condensed', 'mono-led', 'script or hand-drawn accent', 'variable-font axis motion', 'outline or inline',
  'mixed-case editorial', 'small-caps system', 'kinetic type', 'text as image or mask', 'tight setting', 'airy setting',
  'type-only hero, no giant size', 'width as hierarchy', 'hierarchy by weight', 'hierarchy by colour', 'hierarchy by position'];

export async function loadRecipes() {
  const out = [];
  for (const id of readdirSync(root).sort()) {
    const f = join(root, id, 'recipe.mjs');
    if (!statSync(join(root, id)).isDirectory() || !existsSync(f)) continue;
    const r = (await import(pathToFileURL(f).href)).default;
    if (r.id !== id) throw new Error(`${id}: recipe id is ${r.id}`);
    out.push(r);
  }
  return out;
}

const fontLink = (r) => {
  const qs = [...new Set(ROLES.map((k) => r.fonts[k]).filter(Boolean).flatMap((f) => [f.q, ...(f.extra || [])]))];
  return `https://fonts.googleapis.com/css2?${qs.map((q) => 'family=' + q).join('&')}&display=swap`;
};
const stack = (f) => (f ? `"${f.family}", ${f.fallback}` : 'inherit');
const faceLine = (role, f) => (f ? `<div><dt>${role}</dt><dd>${esc(f.family)} <span class="lic">${esc(f.licence)}</span>${f.role ? ' · ' + esc(f.role) : ''}</dd></div>` : '');

