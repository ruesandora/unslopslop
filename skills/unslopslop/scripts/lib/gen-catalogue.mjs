#!/usr/bin/env node
// Writes references/rules.md from rules.mjs so the docs cannot drift from the code.
// `--check` exits 1 when the file on disk is out of date.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { RULES, PASSES, WEIGHTS } from './rules.mjs';
import { BLAND } from './rules-bland.mjs';
import { COMPONENTS, CRAFT_PASS } from './craft.mjs';

export function catalogue() {
  const L = ['# Detection rules', '', '<!-- generated by scripts/lib/gen-catalogue.mjs; do not edit by hand -->', ''];
  L.push(`${RULES.length} rules. Severity weights: critical ${WEIGHTS.critical}, major ${WEIGHTS.major}, minor ${WEIGHTS.minor} points.`);
  L.push('Each extra occurrence adds 25% of the weight, capped at 2x. Score = sum of points, max 100.');
  L.push('Verdict: **heavy** at 35 or more; **clean** below 10 with no critical finding; otherwise **light**.', '');
  L.push('Where: `desktop` = 1440 px, `mobile` = 390 px, `css` rules read the stylesheet text.', '');
  for (const p of PASSES) {
    L.push(`## ${p}`, '', '| Rule | Severity | Where | What it catches | Fix |', '|---|---|---|---|---|');
    for (const r of RULES.filter((x) => x.pass === p)) {
      const where = r.scope === 'css' ? 'css' : r.viewports.join('+');
      L.push(`| \`${r.id}\` | ${r.severity} | ${where} | ${r.title}. ${r.why} | ${r.fix} |`);
    }
    L.push('');
  }
  L.push('# Craft (the other number)', '');
  L.push(`Craft score 0 to 100, higher is better; pass mark ${CRAFT_PASS}. A page passes only with a clean slop verdict and craft at or above the mark.`, '');
  L.push('| Component | Points | Measures |', '|---|---|---|');
  const what = {
    hierarchy: 'display size against body size, and the number of distinct type steps',
    focal: 'one dominant element on the first screen: display headline and/or a large visual',
    visual: 'share of the first screen covered by a real visual (product view, image, canvas, drawing)',
    motion: 'something moves, inside the visual (a demo, not wallpaper), with reduced motion handled',
    identity: 'chosen web font, display face distinct from text face, one accent combination, depth, texture',
    density: 'content on the first screen fits the page type (app screens dense, landings balanced)',
  };
  for (const [k, v] of Object.entries(COMPONENTS)) L.push(`| ${k} | ${v} | ${what[k]} |`);
  L.push('', '## Bland signals', '', 'The opposite failure: a page stripped until nothing is left. These never add to the slop score; they explain a low craft score.', '');
  L.push('| Rule | Severity | What it catches | Fix |', '|---|---|---|---|');
  for (const r of BLAND) L.push(`| \`${r.id}\` | ${r.severity} | ${r.title}. ${r.why} | ${r.fix} |`);
  L.push('');
  return L.join('\n');
}

const file = fileURLToPath(new URL('../../references/rules.md', import.meta.url));
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = catalogue();
  if (process.argv.includes('--check')) {
    const disk = await readFile(file, 'utf8').catch(() => '');
    if (disk !== text) { console.error('references/rules.md is out of date: run npm run catalogue'); process.exit(1); }
  } else {
    await writeFile(file, text);
    console.log(`wrote ${file}`);
  }
}
