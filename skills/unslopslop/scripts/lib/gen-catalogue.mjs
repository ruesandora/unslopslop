#!/usr/bin/env node
// Writes references/rules.md from rules.mjs so the docs cannot drift from the code.
// `--check` exits 1 when the file on disk is out of date.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { RULES, PASSES, WEIGHTS } from './rules.mjs';

export function catalogue() {
  const L = ['# Detection rules', '', '<!-- generated by scripts/lib/gen-catalogue.mjs; do not edit by hand -->', ''];
  L.push(`${RULES.length} rules. Severity weights: critical ${WEIGHTS.critical}, major ${WEIGHTS.major}, minor ${WEIGHTS.minor} points.`);
  L.push('Each extra occurrence adds 25% of the weight, capped at 2x. Score = sum of points, max 100.');
  L.push('Verdict: **heavy** at 35 or more; **clean** below 10 with no critical finding; otherwise **light**.', '');
  L.push('Where: `desktop` = 1440 px, `mobile` = 390 px, `css` rules read the stylesheet text.', '');
  for (const p of PASSES) {
    L.push(`## ${p}`, '', '| Rule | Severity | Where | What it catches | Fix |', '|---|---|---|---|---|');
    for (const r of RULES.filter((x) => x.pass === p)) {
      const where = r.scope === 'css' ? 'css' : r.viewports.join('+');
      L.push(`| \`${r.id}\` | ${r.severity} | ${where} | ${r.title}. ${r.why} | ${r.fix} |`);
    }
    L.push('');
  }
  return L.join('\n');
}

const file = fileURLToPath(new URL('../../references/rules.md', import.meta.url));
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = catalogue();
  if (process.argv.includes('--check')) {
    const disk = await readFile(file, 'utf8').catch(() => '');
    if (disk !== text) { console.error('references/rules.md is out of date: run npm run catalogue'); process.exit(1); }
  } else {
    await writeFile(file, text);
    console.log(`wrote ${file}`);
  }
}
